"""Generate the player-card WOFF2 slices and their TypeScript cmap manifest."""

import argparse
from io import BytesIO
from itertools import batched
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "public/fonts/player-card"
MANIFEST = ROOT / "src/views/DrawTools/PlayerCard/nicknameFontSlices.ts"
MAX_RARE_BYTES = 400_000
TARGET_COUNT = 1000


def common_codepoints():
    points = {0x709C, 0x96BD}
    for start, end in [(0x20, 0x7E), (0xA0, 0x24F), (0x2000, 0x206F),
                       (0x3000, 0x303F), (0xFF00, 0xFFEF)]:
        points.update(range(start, end + 1))
    for lead in range(0xB0, 0xD8):
        row = b"".join(bytes((lead, trail)) for trail in range(0xA1, 0xFF))
        points.update(map(ord, row.decode("gb2312", errors="ignore")))
    return points


def compress_slice(sfnt, points):
    with TTFont(BytesIO(sfnt), recalcTimestamp=False) as font:
        subsetter = subset.Subsetter(options=subset.Options(
            layout_features=["*"], name_IDs=["*"], name_languages=["*"], glyph_names=False,
        ))
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        output = BytesIO()
        font.flavor = "woff2"
        font.save(output)
        return output.getvalue()


def manifest_entry(filename, points):
    ranges = []
    for point in sorted(points):
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    pairs = (f"[{start},{end}]" for start, end in ranges)
    lines = ["    " + ", ".join(group) + "," for group in batched(pairs, 8)]
    return f'  slice("{filename}", [\n' + "\n".join(lines) + "\n  ]),\n"


def generate(source):
    with TTFont(source, recalcTimestamp=False) as font:
        mapped = set(font.getBestCmap())
        assert len(mapped) == 16_739
        unpacked = BytesIO()
        font.flavor = None
        font.save(unpacked)
        sfnt = unpacked.getvalue()

    directory = FONT_DIR / "slices"
    directory.mkdir(exist_ok=True)
    entries = []
    seen = set()

    def write_slice(filename, points, data):
        path = directory / filename
        path.write_bytes(data)
        with TTFont(path) as saved:
            actual = set(saved.getBestCmap())
        assert actual == set(points) and seen.isdisjoint(actual), filename
        seen.update(actual)
        entries.append(manifest_entry(filename, actual))
        print(f"{filename}: {path.stat().st_size} bytes, {len(actual)} code points", flush=True)

    common = mapped & common_codepoints()
    write_slice("common.woff2", common, compress_slice(sfnt, common))
    rare = sorted(mapped - common)
    offset = 0
    count = TARGET_COUNT
    while offset < len(rare):
        points = rare[offset:offset + count]
        data = compress_slice(sfnt, points)
        next_count = min(TARGET_COUNT, len(points) * (MAX_RARE_BYTES * 98 // 100) // len(data))
        if len(data) <= MAX_RARE_BYTES:
            write_slice(f"rare-{len(entries):02}.woff2", points, data)
            offset += len(points)
        count = next_count

    assert seen == mapped
    MANIFEST.write_text('''// Generated by scripts/split-player-card-font.py. Do not edit.
export type NicknameFontSlice = {
  readonly file: string;
  readonly unicodeRange: string;
  readonly ranges: readonly (readonly [number, number])[];
};

function slice(filename: string, ranges: NicknameFontSlice["ranges"]): NicknameFontSlice {
  return {
    file: `/fonts/player-card/slices/${filename}`,
    ranges,
    get unicodeRange() {
      return ranges.map(([start, end]) => start === end
        ? `U+${start.toString(16)}`
        : `U+${start.toString(16)}-${end.toString(16)}`).join(",");
    },
  };
}

export const NICKNAME_FONT_SLICES: readonly NicknameFontSlice[] = [
''' + "".join(entries) + "];\n", encoding="utf-8")
    print(f"Verified {len(seen):,} mapped code points; zero overlap.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?", type=Path, default=FONT_DIR / "the-peak-font-plus.woff2")
    generate(parser.parse_args().source)
